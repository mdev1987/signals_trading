#!/usr/bin/env python3
"""Partition filtered PumpAPI JSONL.ZST events by Mint without changing raw lines.

The partitioner uses the per-file/per-mint counts from filtered_replay_report.json
for a balanced, deterministic grouping. Each Mint is assigned to exactly one batch.
Within every batch, source file order and raw line order are preserved.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
import sys
from collections import Counter
from contextlib import ExitStack
from pathlib import Path
from typing import Any

try:
    import orjson

    def loads(value: bytes) -> Any:
        return orjson.loads(value)
except ImportError:
    def loads(value: bytes) -> Any:
        return json.loads(value)

try:
    import zstandard as zstd
except ImportError as exc:  # pragma: no cover - environment error
    raise SystemExit("Missing dependency: run `uv add zstandard`.") from exc


def read_zstd_lines(path: Path):
    with path.open("rb") as source:
        reader = zstd.ZstdDecompressor().stream_reader(
            source, read_across_frames=True
        )
        with io.BufferedReader(reader, buffer_size=4 << 20) as stream:
            yield from stream


def event_mint_and_timestamp(raw: bytes, *, path: Path, line_no: int):
    try:
        event = loads(raw)
    except Exception as exc:
        raise ValueError(
            f"Invalid JSON in filtered input {path}:{line_no}: {exc}"
        ) from exc
    if not isinstance(event, dict):
        raise ValueError(f"Non-object JSON in filtered input {path}:{line_no}")
    mint = event.get("mint")
    if not isinstance(mint, str) or not mint:
        raise ValueError(f"Missing top-level mint in {path}:{line_no}")
    timestamp = event.get("timestamp", event.get("timestamp_ms"))
    if isinstance(timestamp, bool):
        raise ValueError(f"Invalid timestamp in {path}:{line_no}")
    try:
        timestamp_ms = int(timestamp)
    except (TypeError, ValueError, OverflowError) as exc:
        raise ValueError(f"Invalid timestamp in {path}:{line_no}") from exc
    return mint, timestamp_ms


def best_fit_groups(counts: dict[str, int], limit: int):
    """Best-fit-decreasing bin pack. Oversized mints remain alone in a batch."""
    bins: list[dict[str, Any]] = []
    for mint, count in sorted(counts.items(), key=lambda item: (-item[1], item[0])):
        candidates = [
            (limit - item["expected_events"], index)
            for index, item in enumerate(bins)
            if item["expected_events"] + count <= limit
        ]
        if candidates:
            _, index = min(candidates)
            bins[index]["mints"].append(mint)
            bins[index]["expected_events"] += count
        else:
            bins.append({"mints": [mint], "expected_events": count})
    for item in bins:
        item["mints"].sort()
    return bins


def parse_args():
    parser = argparse.ArgumentParser(
        description="Split filtered replay into balanced, whole-Mint Zstandard batches."
    )
    parser.add_argument("--input-dir", type=Path, required=True)
    parser.add_argument("--targets", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True,
                        help="filtered_replay_report.json generated by filter_replay.py")
    parser.add_argument("--diagnostics", type=Path, required=True,
                        help="filter_replay_diagnostics.json confirming top-level Mint matches")
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--max-events-per-batch", type=int, default=100_000)
    parser.add_argument("--level", type=int, default=3)
    parser.add_argument("--overwrite", action="store_true")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    if args.max_events_per_batch < 1:
        raise SystemExit("--max-events-per-batch must be positive")
    if not 1 <= args.level <= 19:
        raise SystemExit("--level must be between 1 and 19")

    targets = {
        line.strip()
        for line in args.targets.read_text(encoding="utf-8").splitlines()
        if line.strip()
    }
    if not targets:
        raise SystemExit("Target mint list is empty")

    source_report = json.loads(args.report.read_text(encoding="utf-8"))
    diagnostics = json.loads(args.diagnostics.read_text(encoding="utf-8"))
    if diagnostics.get("passed") is not True:
        raise SystemExit("Filter diagnostics are not passed=true")
    classification = diagnostics.get("classification", {})
    if classification.get("json_decode_errors", 0) != 0:
        raise SystemExit("Diagnostics found invalid JSON in selected lines")
    if classification.get("valid_non_object_json", 0) != 0:
        raise SystemExit("Diagnostics found selected non-object JSON records")
    if diagnostics.get("legacy_malformed_count_matches") is not True:
        raise SystemExit("Legacy malformed count is not explained by diagnostics")
    if diagnostics.get("exact_top_level_matches_reconciled") is not True:
        raise SystemExit("Top-level exact-Mint event count does not reconcile")
    if diagnostics.get("out_of_hour_reconciled") is not True:
        raise SystemExit("Boundary events do not reconcile")
    if diagnostics.get("timestamp_inversion_examples"):
        raise SystemExit("Diagnostics found timestamp inversions")
    if classification.get("top_level_mint_missing_or_invalid", 0) != source_report.get("malformed_selected_events"):
        raise SystemExit("Legacy malformed count does not match missing top-level Mint count")
    if source_report.get("passed") is not True and source_report.get("malformed_selected_events") != 0:
        print(
            "NOTE: source filter report passed=false only because its legacy regex "
            "counter labels top-level-mint-missing records as malformed; the separate "
            "diagnostics report has reconciled these records. Continuing with exact "
            "top-level Mint matches.",
            file=sys.stderr,
        )
    elif source_report.get("passed") is not True:
        raise SystemExit("Filtered replay source report is not passed=true")
    if source_report.get("target_mint_count") != len(targets):
        raise SystemExit("Target count does not match filtered replay report")
    if source_report.get("hours_processed") != source_report.get("hours_requested"):
        raise SystemExit("Not all requested replay hours were processed")
    if source_report.get("output_verification_errors") != 0:
        raise SystemExit("Filtered replay report contains output verification errors")

    file_reports = source_report.get("files")
    if not isinstance(file_reports, list) or not file_reports:
        raise SystemExit("Filtered replay report has no per-file records")

    expected_by_file: dict[str, dict[str, int]] = {}
    total_by_mint: Counter[str] = Counter()
    source_files: list[Path] = []
    expected_total = 0

    for item in file_reports:
        name = item.get("output_file")
        per_mint = item.get("events_by_mint")
        if not isinstance(name, str) or not isinstance(per_mint, dict):
            raise SystemExit("Per-file report is missing output_file/events_by_mint")
        path = args.input_dir / name
        if not path.is_file():
            raise FileNotFoundError(path)
        if item.get("output_verification_errors") != 0:
            raise SystemExit(f"Input archive has verification errors: {name}")
        if item.get("output_verified_lines") != item.get("matched_event_lines"):
            raise SystemExit(f"Input archive line counts do not reconcile: {name}")
        if any(mint not in targets for mint in per_mint):
            raise SystemExit(f"Unexpected Mint in source report: {name}")
        per_mint_int = {str(mint): int(count) for mint, count in per_mint.items()}
        expected_by_file[name] = per_mint_int
        total_by_mint.update(per_mint_int)
        expected_total += int(item["matched_event_lines"])
        source_files.append(path)

    if set(total_by_mint) != targets:
        missing = sorted(targets - set(total_by_mint))
        extra = sorted(set(total_by_mint) - targets)
        raise SystemExit(f"Target/report Mint mismatch; missing={missing}, extra={extra}")
    if sum(total_by_mint.values()) != expected_total:
        raise SystemExit("Per-Mint source counts do not match total matched_event_lines")
    if expected_total != source_report.get("matching_events_written"):
        raise SystemExit("Source report global event count does not reconcile")

    groups = best_fit_groups(dict(total_by_mint), args.max_events_per_batch)
    mint_to_batch = {
        mint: index for index, group in enumerate(groups) for mint in group["mints"]
    }

    args.output_dir.mkdir(parents=True, exist_ok=True)
    existing = list(args.output_dir.glob("mint_batch_*.jsonl.zst"))
    manifest_path = args.output_dir / "shard_manifest.json"
    if (existing or manifest_path.exists()) and not args.overwrite:
        raise SystemExit(
            f"Output already contains shard files. Use --overwrite: {args.output_dir}"
        )
    if args.overwrite:
        for path in existing:
            path.unlink()
        if manifest_path.exists():
            manifest_path.unlink()

    compressor = zstd.ZstdCompressor(level=args.level)
    writers = []
    output_paths = []
    hashes = [hashlib.sha256() for _ in groups]
    written_by_mint = [Counter() for _ in groups]
    written_by_file = {path.name: Counter() for path in source_files}
    written_by_batch_file = [Counter() for _ in groups]
    global_last_timestamp = None
    timestamp_inversions = []
    source_lines_read = 0
    selected_lines_written = 0

    try:
        with ExitStack() as stack:
            for index in range(len(groups)):
                output_path = args.output_dir / f"mint_batch_{index:03d}.jsonl.zst"
                raw_out = stack.enter_context(output_path.open("wb"))
                writer = stack.enter_context(
                    compressor.stream_writer(raw_out, closefd=False)
                )
                writers.append(writer)
                output_paths.append(output_path)

            for source_path in source_files:
                file_counts = Counter()
                for line_no, raw in enumerate(read_zstd_lines(source_path), start=1):
                    source_lines_read += 1
                    mint, timestamp_ms = event_mint_and_timestamp(
                        raw, path=source_path, line_no=line_no
                    )
                    batch = mint_to_batch.get(mint)
                    if batch is None:
                        raise ValueError(
                            f"Unexpected top-level Mint {mint} in {source_path}:{line_no}"
                        )
                    if global_last_timestamp is not None and timestamp_ms < global_last_timestamp:
                        if len(timestamp_inversions) < 20:
                            timestamp_inversions.append({
                                "file": source_path.name,
                                "line": line_no,
                                "timestamp_ms": timestamp_ms,
                                "previous_timestamp_ms": global_last_timestamp,
                            })
                    global_last_timestamp = timestamp_ms

                    writers[batch].write(raw)
                    hashes[batch].update(raw)
                    written_by_mint[batch][mint] += 1
                    written_by_file[source_path.name][mint] += 1
                    written_by_batch_file[batch][source_path.name] += 1
                    file_counts[mint] += 1
                    selected_lines_written += 1

                expected = expected_by_file[source_path.name]
                if dict(file_counts) != expected:
                    missing = expected - file_counts
                    extra = file_counts - Counter(expected)
                    raise RuntimeError(
                        f"Per-file/per-Mint mismatch for {source_path.name}: "
                        f"missing={dict(missing)}, extra={dict(extra)}"
                    )

    except Exception:
        # Remove incomplete output files so a retry cannot mistake them for a pass.
        for path in output_paths:
            try:
                path.unlink(missing_ok=True)
            except OSError:
                pass
        raise

    verification = []
    verification_errors = 0
    for index, output_path in enumerate(output_paths):
        observed = Counter()
        line_count = 0
        digest = hashlib.sha256()
        previous_ts = None
        inversions = 0
        allowed = set(groups[index]["mints"])

        for line_no, raw in enumerate(read_zstd_lines(output_path), start=1):
            line_count += 1
            digest.update(raw)
            try:
                mint, timestamp_ms = event_mint_and_timestamp(
                    raw, path=output_path, line_no=line_no
                )
            except ValueError:
                verification_errors += 1
                continue
            if mint not in allowed:
                verification_errors += 1
            observed[mint] += 1
            if previous_ts is not None and timestamp_ms < previous_ts:
                inversions += 1
            previous_ts = timestamp_ms

        expected_counts = written_by_mint[index]
        hash_matches = digest.hexdigest() == hashes[index].hexdigest()
        counts_match = observed == expected_counts
        if not hash_matches or not counts_match or line_count != sum(expected_counts.values()):
            verification_errors += 1
        if inversions:
            verification_errors += inversions

        verification.append({
            "batch": index,
            "file": output_path.name,
            "mints": len(allowed),
            "expected_events": sum(expected_counts.values()),
            "verified_events": line_count,
            "compressed_bytes": output_path.stat().st_size,
            "raw_sha256_matches": hash_matches,
            "per_mint_counts_match": counts_match,
            "timestamp_inversions": inversions,
            "events_by_source_file": dict(written_by_batch_file[index]),
            "mints_in_batch": groups[index]["mints"],
        })

    output_bytes = sum(path.stat().st_size for path in output_paths)
    passed = (
        verification_errors == 0
        and not timestamp_inversions
        and selected_lines_written == expected_total
        and len(set(mint_to_batch)) == len(targets)
        and all(item["raw_sha256_matches"] and item["per_mint_counts_match"] for item in verification)
    )

    manifest = {
        "version": "1.0.0",
        "passed": passed,
        "partition_policy": "whole-Mint best-fit-decreasing; all actions retained; source file and line order preserved per batch; raw lines byte-identical",
        "source_input_dir": str(args.input_dir),
        "source_report": str(args.report),
        "filter_diagnostics": str(args.diagnostics),
        "source_report_legacy_passed": source_report.get("passed"),
        "diagnostics_passed": diagnostics.get("passed"),
        "explained_nested_mint_records": classification.get("top_level_mint_missing_or_invalid", 0),
        "target_mints": len(targets),
        "source_files": len(source_files),
        "source_lines_read": source_lines_read,
        "expected_events": expected_total,
        "events_written": selected_lines_written,
        "verified_events": sum(item["verified_events"] for item in verification),
        "max_events_per_batch_target": args.max_events_per_batch,
        "batch_count": len(groups),
        "largest_batch_events": max(item["expected_events"] for item in verification),
        "largest_single_mint_events": max(total_by_mint.values()),
        "source_timestamp_inversions": timestamp_inversions,
        "verification_errors": verification_errors,
        "compressed_output_bytes": output_bytes,
        "compressed_input_bytes": sum(path.stat().st_size for path in source_files),
        "compressed_size_fraction": (
            output_bytes / sum(path.stat().st_size for path in source_files)
            if source_files else None
        ),
        "events_by_action": dict(source_report.get("action_counts", {})),
        "events_by_pool": dict(source_report.get("pool_counts", {})),
        "per_mint_event_count_range": {
            "min": min(total_by_mint.values()),
            "median": sorted(total_by_mint.values())[len(total_by_mint) // 2],
            "max": max(total_by_mint.values()),
        },
        "batches": verification,
    }
    manifest_path.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

    summary = {key: value for key, value in manifest.items() if key != "batches"}
    summary["batch_summaries"] = [
        {
            "batch": item["batch"],
            "file": item["file"],
            "mints": item["mints"],
            "expected_events": item["expected_events"],
            "verified_events": item["verified_events"],
            "compressed_bytes": item["compressed_bytes"],
            "timestamp_inversions": item["timestamp_inversions"],
            "raw_sha256_matches": item["raw_sha256_matches"],
        }
        for item in verification
    ]
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    print(f"\nSaved: {manifest_path}")
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
